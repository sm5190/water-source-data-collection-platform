"""Build config/cities.yaml from the project workbook (Sarina Water Source.xlsx).

The 'Standardization' sheet is the canonical source (city, state/province, country,
coordinates). Cities that only appear in 'Sheet1'/'Updates' are added when neither their
name nor an alias (text in parentheses) is already present. Country spellings are normalized.

Usage: uv run python scripts/build_city_catalog.py "<path to workbook>" [config/cities.yaml]
"""

import re
import sys
from pathlib import Path
import openpyxl
import yaml

COUNTRY_ALIASES = {"usa": "United States of America", "england": "United Kingdom"}

def clean(value) -> str:
    return " ".join(str(value or "").split())

def names(city: str) -> set[str]:
    """'Pune (Poona)' -> {'pune (poona)', 'pune', 'poona'}."""
    out = {city.casefold()}
    m = re.match(r"^(.*?)\s*\((.*)\)\s*$", city)
    if m:
        out |= {m.group(1).casefold(), m.group(2).casefold()}
    return out

def aliases(city: str) -> list[str]:
    m = re.match(r"^(.*?)\s*\((.*)\)\s*$", city)
    return [m.group(1), m.group(2)] if m else []

def country(value) -> str:
    c = clean(value)
    return COUNTRY_ALIASES.get(c.casefold(), c)

def build(workbook: Path) -> list[dict]:
    wb = openpyxl.load_workbook(workbook, read_only=True, data_only=True)
    catalog: list[dict] = []
    known: set[str] = set()

    def add(entry: dict) -> None:
        keys = names(entry["city"])
        if keys & known:
            return
        known.update(keys)
        catalog.append(entry)

    for row in list(wb["Standardization"].iter_rows(values_only=True))[1:]:
        city = clean(row[0])
        if not city:
            continue
        add({"city": city, "jurisdiction": clean(row[1]) or None, "country": country(row[2]),
             "latitude": row[3] if isinstance(row[3], (int, float)) else None,
             "longitude": row[4] if isinstance(row[4], (int, float)) else None,
             "aliases": aliases(city), "source": "Standardization"})
    for sheet in ("Sheet1", "Updates"):
        for row in list(wb[sheet].iter_rows(values_only=True))[1:]:
            city = clean(row[0])
            if city:
                add({"city": city, "jurisdiction": None, "country": country(row[1]),
                     "latitude": None, "longitude": None, "aliases": aliases(city),
                     "source": sheet})
    return sorted(catalog, key=lambda c: (c["country"].casefold(), c["city"].casefold()))

def main() -> None:
    workbook = Path(sys.argv[1])
    out = Path(sys.argv[2] if len(sys.argv) > 2 else "config/cities.yaml")
    catalog = build(workbook)
    header = (f"# Generated by scripts/build_city_catalog.py from {workbook.name}. "
              "Edit the workbook and regenerate.\n")
    out.write_text(header + yaml.safe_dump({"version": 1, "cities": catalog},
                                           allow_unicode=True, sort_keys=False),
                   encoding="utf-8")
    print(f"wrote {len(catalog)} cities to {out}")

if __name__ == "__main__":
    main()
